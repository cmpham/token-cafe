// Generate src/assets.rs and src/bg.rgb from design/cafe.js, the single
// source of the art.
//   node tools/gen_assets.mjs
// Sprites become slot-indexed bytes (one slot per palette character, 0 =
// transparent); colours become 0xRRGGBB as the design defines them; the
// static room (background + empty message window) becomes a 480x272 RGB
// image next to the module.
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const A = require(path.join(here, '../design/cafe.js')).exportAssets();

const hex = v => '0x' + v.toString(16).padStart(6, '0');
const col = ([r, g, b]) => hex((r << 16) | (g << 8) | b);
const scream = k => k.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();     // wallA -> WALL_A

/* ---- every sprite, with a Rust name ---- */
const sprites = [];   // [name, sprite]
const add = (name, s) => { sprites.push([name, s]); return name; };
for (const [k, s] of Object.entries(A.HEAD)) add(`HEAD_${scream(k)}`, s);
add('CHAIR', A.CHAIR); add('LID', A.LID);
A.SPARK.forEach((s, i) => add(`SPARK_${i}`, s));
A.PROMPT.forEach((s, i) => add(`PROMPT_${i}`, s));
for (const [k, s] of Object.entries(A.PROPS)) add(`PROP_${scream(k)}`, s);
for (const [k, s] of Object.entries(A.BUBBLE)) add(`BUBBLE_${scream(k)}`, s);
add('ZSMALL', A.ZSMALL); add('ZBIG', A.ZBIG);
A.KEYS.forEach((s, i) => add(`KEY_${i}`, s));
add('CURSOR', A.CURSOR);
for (const [k, s] of Object.entries(A.ICON)) add(`ICON_${scream(k)}`, s);
const POSE_FIELDS = ['standD', 'walkD', 'standU', 'walkU', 'standS', 'walkS', 'type', 'think', 'raise', 'stretch', 'sip', 'sleep'];
const field = f => f === 'type' ? 'typing' : f.replace(/[A-Z]/g, c => '_' + c.toLowerCase());
for (const st of A.HAIR_STYLES) for (const f of POSE_FIELDS) {
    const v = A.POSES[st][f];
    if (Array.isArray(v)) v.forEach((s, i) => add(`POSE_${scream(st)}_${scream(f)}_${i}`, s)); else add(`POSE_${scream(st)}_${scream(f)}`, v);
}

/* ---- slots: BASE characters first, then everything else in use ---- */
const used = new Set();
for (const [, s] of sprites) for (const r of s.rows) for (const ch of r) if (ch !== '.') used.add(ch);
const slots = ['.'];
for (const ch of Object.keys(A.BASE)) if (!slots.includes(ch)) slots.push(ch);
for (const ch of [...used].sort()) if (!slots.includes(ch)) slots.push(ch);
for (const ch of 'HhJSsCcVPFAaLl') if (!slots.includes(ch)) slots.push(ch);
if (slots.length > 64) throw new Error('more than 64 palette slots');
const slotOf = Object.fromEntries(slots.map((ch, i) => [ch, i]));

const R = [];
R.push('//! Generated by tools/gen_assets.mjs from design/cafe.js. Do not edit.');
R.push('#![allow(non_upper_case_globals, dead_code)]', '');
R.push(`pub const W: usize = ${A.W};`, `pub const H: usize = ${A.H};`, `pub const WIN_Y: i32 = ${A.WIN_Y};`,
       `pub const SLOTS: usize = ${slots.length};`, '');
R.push('/// Palette slots: one per sprite character.');
R.push('pub mod slot {', ...slots.slice(1).map((ch, i) => `    pub const ${ch}: usize = ${i + 1};`), '}', '');
R.push('#[derive(Clone, Copy)]', 'pub struct Sprite { pub w: u8, pub h: u8, pub px: &\'static [u8] }', '');
R.push('#[derive(Clone, Copy)]', 'pub struct Pal { pub c: [u32; SLOTS], pub set: u64 }', '');
R.push('/// Colours every sprite may use, 0xRRGGBB.');
R.push('pub mod base {', ...Object.entries(A.BASE).map(([k, v]) => `    pub const ${k}: u32 = ${col(v)};`), '}', '');
R.push('/// Scene colours, 0xRRGGBB.');
R.push('pub mod c {', ...Object.entries(A.C).map(([k, v]) => `    pub const ${scream(k)}: u32 = ${col(v)};`), '}', '');
R.push(`pub const LOOK_V: u32 = ${col(A.LOOK_V)};`, `pub const LOOK_F: u32 = ${col(A.LOOK_F)};`,
       `pub const IDLE_TEXT: u32 = ${col(A.IDLE_TEXT)};`, `pub const ICON_LAPTOP_A: u32 = ${col(A.ICON_LAPTOP_A)};`,
       `pub const ICON_LAPTOP_a: u32 = ${col(A.ICON_LAPTOP_a)};`, '');

const base = Array(slots.length).fill(hex(0)); let set = 0n;
for (const [ch, v] of Object.entries(A.BASE)) { base[slotOf[ch]] = col(v); set |= 1n << BigInt(slotOf[ch]); }
R.push(`pub static BASE_PAL: Pal = Pal { c: [${base.join(', ')}], set: 0x${set.toString(16)} };`, '');
const lap = k => ['L', 'l', 'A', 'a'].map(n => col(A.LAPTOP[k][n])).join(', ');
R.push(`/// [claude, codex][L, l, A, a]`, `pub static LAPTOP: [[u32; 4]; 2] = [[${lap('claude')}], [${lap('codex')}]];`);
const arr2 = a => a.map(p => `[${p.map(col).join(', ')}]`).join(', ');
R.push(`pub static SKINS: [[u32; 2]; ${A.SKINS.length}] = [${arr2(A.SKINS)}];`);
R.push(`pub static HAIRS: [[u32; 3]; ${A.HAIRS.length}] = [${arr2(A.HAIRS)}];`);
R.push(`pub static SHIRTS: [[u32; 2]; ${A.SHIRTS.length}] = [${arr2(A.SHIRTS)}];`);
R.push(`pub static PANTS: [u32; ${A.PANTS.length}] = [${A.PANTS.map(col).join(', ')}];`);
R.push(`pub static CHAIRS: [[u32; 2]; ${A.CHAIRS.length}] = [${arr2(A.CHAIRS)}];`, '');

const lit = name => {
    const s = sprites.find(([n]) => n === name)[1];
    const rows = s.rows.map(r => '        ' + [...r].map(ch => slotOf[ch]).join(',') + ',');
    return [`Sprite { w: ${s.w}, h: ${s.h}, px: &[`, ...rows, '    ] }'];
};
for (const [name] of sprites) {
    if (name.startsWith('POSE_')) continue;
    const l = lit(name);
    R.push(`pub static ${name}: Sprite = ${l[0]}`, ...l.slice(1, -1), '] };');
}
R.push('');
const group = (name, prefix, n) => R.push(`pub static ${name}: [Sprite; ${n}] = [${Array.from({ length: n }, (_, i) => `${prefix}_${i}`).join(', ')}];`);
group('SPARK', 'SPARK', A.SPARK.length);
group('PROMPT', 'PROMPT', A.PROMPT.length);
group('KEYS', 'KEY', A.KEYS.length);
R.push('');

R.push('pub struct Poses {');
for (const f of POSE_FIELDS) {
    const v = A.POSES.short[f];
    R.push(`    pub ${field(f)}: ${Array.isArray(v) ? `[Sprite; ${v.length}]` : 'Sprite'},`);
}
R.push('}', '');
for (const st of A.HAIR_STYLES) for (const f of POSE_FIELDS) {
    const v = A.POSES[st][f];
    const names = Array.isArray(v) ? v.map((_, i) => `POSE_${scream(st)}_${scream(f)}_${i}`) : [`POSE_${scream(st)}_${scream(f)}`];
    for (const name of names) {
        const l = lit(name);
        R.push(`const ${name}: Sprite = ${l[0]}`, ...l.slice(1, -1), '] };');
    }
}
R.push(`/// ${A.HAIR_STYLES.join(', ')}`, `pub static POSES: [Poses; ${A.HAIR_STYLES.length}] = [`);
for (const st of A.HAIR_STYLES) {
    R.push('    Poses {');
    for (const f of POSE_FIELDS) {
        const v = A.POSES[st][f];
        R.push(Array.isArray(v)
            ? `        ${field(f)}: [${v.map((_, i) => `POSE_${scream(st)}_${scream(f)}_${i}`).join(', ')}],`
            : `        ${field(f)}: POSE_${scream(st)}_${scream(f)},`);
    }
    R.push('    },');
}
R.push('];', '');

const font = [], has = [];
for (let c = 32; c < 128; c++) {
    const g = A.GLYPH[String.fromCharCode(c)];
    has.push(!!g);
    font.push(g ? g.map(r => parseInt(r.replace(/#/g, '1').replace(/\./g, '0'), 2)) : [0, 0, 0, 0, 0, 0, 0]);
}
R.push('/// 5x7 font for ASCII 32..127: one byte per row, bit 4 = leftmost pixel.');
R.push('pub static FONT: [[u8; 7]; 96] = [',
       ...font.map((g, i) => `    [${g.map(v => '0x' + v.toString(16).padStart(2, '0')).join(', ')}],  // ${JSON.stringify(String.fromCharCode(32 + i))}`), '];');
R.push(`pub static FONT_HAS: [bool; 96] = [${has.join(', ')}];`, '');

R.push('/// The static room: background plus the empty message window, 8-bit RGB.');
R.push('pub static BG: &[u8; W * H * 3] = include_bytes!("bg.rgb");', '');

const bg = Buffer.alloc(A.W * A.H * 3);
for (let p = 0; p < A.W * A.H; p++) for (let c = 0; c < 3; c++) bg[p * 3 + c] = A.bg[p * 4 + c];

const out = path.join(here, '../src');
fs.writeFileSync(path.join(out, 'assets.rs'), R.join('\n'));
fs.writeFileSync(path.join(out, 'bg.rgb'), bg);
console.log(`assets: ${sprites.length} sprites, ${slots.length} slots, font ${has.filter(Boolean).length} glyphs, bg ${A.W}x${A.H}`);
